/**
 * Пометка источника записи журнала.
 *
 * В журнале два вида записей:
 *   * живые прогнозы — сделаны до матча, тем же кодом, что работает
 *     сейчас (models/*_predict.py);
 *   * walk-forward (WF) — оценка модели на истории: модель обучена на
 *     прошлых сезонах и «предсказывает» уже сыгранные матчи
 *     (models/*_backtest.py).
 *
 * Раньше оба вида лежали в одном файле, и walk-forward запись этапа
 * T-24h затирала живой прогноз того же матча. Теперь журналы раздельные,
 * а в строке видно, откуда она взялась: незамеченная подмена «что мы
 * сказали до матча» на «что сказал бэктест» — это и есть нечестная
 * статистика.
 */
export function JournalSourceBadge({
  source,
}: {
  source?: string | null;
}) {
  if (source !== "backtest") return null;
  return (
    <span
      className="ml-1 rounded bg-panel-2 px-1 py-0.5 text-[10px] align-middle text-muted"
      title="Walk-forward: модель обучена на прошлых сезонах, прогноз сделан после матча"
    >
      WF
    </span>
  );
}
