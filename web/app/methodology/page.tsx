import { getBacktest, getCalibration, getValidation } from "@/lib/data";

export const dynamic = "force-dynamic";

function Section({
  title,
  children,
}: {
  title: string;
  children: React.ReactNode;
}) {
  return (
    <section className="panel p-5">
      <h2 className="mb-2 text-sm font-semibold">{title}</h2>
      <div className="space-y-2 text-sm text-muted">{children}</div>
    </section>
  );
}

export default async function MethodologyPage() {
  const [backtest, calibration, validation] = await Promise.all([
    getBacktest(),
    getCalibration(),
    getValidation(),
  ]);

  const seasons = validation?.coverage.length ?? 0;
  const totalMatches =
    validation?.coverage.reduce((s, c) => s + c.matches, 0) ?? 0;

  return (
    <div className="space-y-4">
      <div>
        <h1 className="text-lg font-semibold">Методика</h1>
        <p className="mt-1 text-sm text-muted">
          Как считаются прогнозы и почему им нельзя доверять как источнику
          прибыли. Описание честное: сначала ограничения, потом метод.
        </p>
      </div>

      <Section title="Главное ограничение">
        <p>
          На отложенных сезонах модель даёт log-loss{" "}
          <span className="num text-text">
            {backtest?.test.find((r) => r.model.startsWith("blend"))?.logloss.toFixed(5) ??
              "—"}
          </span>{" "}
          против{" "}
          <span className="num text-text">
            {backtest?.test.find((r) => r.model.startsWith("market"))?.logloss.toFixed(5) ??
              "—"}
          </span>{" "}
          у закрывающей линии букмекеров. Рынок агрегирует котировки десятков
          компаний и уже содержит почти всю доступную информацию о матче.
          Публикуем это, а не прячем: понятный проигрыш полезнее неясной
          уверенности.
        </p>
      </Section>

      <Section title="Данные">
        <p>
          <span className="num text-text">{totalMatches}</span> матчей,{" "}
          <span className="num text-text">{seasons}</span> сезонов Primeira Liga с
          2000/01. Источники: football-data.co.uk — результаты, статистика матча
          (удары, удары в створ, угловые, карточки) и коэффициенты 10+
          букмекеров, включая закрывающие; football-data.org — расписание
          будущих матчей, таблица и официальные названия клубов.
        </p>
        <p>
          Схема колонок у CSV менялась между сезонами (от 22 до 119 колонок),
          поэтому парсер работает строго по заголовкам, а не по индексам. Названия
          клубов приведены к общему справочнику: <span className="num">Sp Lisbon</span>,{" "}
          <span className="num">Setubal</span> и другие варианты writings сходятся
          к одному идентификатору.
        </p>
      </Section>

      <Section title="Чего в данных нет">
        <p>
          xG есть только в сезоне 2026/27. Удары в створ — с 2017/18. Закрывающие
          коэффициенты — с 2019/20, то есть сравнение с рынком возможно только на
          семи сезонах, около 2200 матчей. Составы, травмы и новости о
          переводах недоступны в бесплатных источниках.
        </p>
        <p>
          Именно с этим ограничением связано отставание от рынка: у букмекера есть
          информация о составах, а у модели — нет.
        </p>
      </Section>

      <Section title="Модели">
        <p>
          <span className="font-medium text-text">Elo.</span> Рейтинг обновляется
          онлайн, в хронологическом порядке. Коэффициент «разница рейтингов →
          разница мячей» не задан вручную, а накапливается обычной регрессией
          по сыгранным матчам, поэтому подстраивается под лигу. Между сезонами
          рейтинг не обнуляется, а подтягивается к среднему.
        </p>
        <p>
          <span className="font-medium text-text">Dixon-Coles.</span> Пуассоновская
          модель голов: <span className="num">lambda = exp(атака − оборона)</span>,
          плюс домашнее преимущество и поправка на зависимость исходов при низких
          счётах. Оценивается максимумом правдоподобия с экспоненциальным
          затуханием: матч пятилетней давности весит в 32 раза меньше вчерашнего.
        </p>
        <p>
          Обратите внимание на знак обороны. Параметр вычитается, поэтому{" "}
          <strong className="font-medium text-text">
            больше обороны означает лучшую оборону
          </strong>{" "}
          — чем выше значение, тем меньше забивает соперник. Обе величины
          читаются одинаково, «больше — лучше», и сила команды это их сумма, а не
          разность. Положить наоборот — типичная ошибка, из-за которой
          сильнейшие клубы лиги выглядят слабейшими.
        </p>
        <p>
          Важная тонкость: сила команды одновременно выражается через её атаку и
          через оборону соперников. Если штрафовать только одну сторону,
          оптимизатор выберет непштрафованную, и модель выродится в «все
          одинаковые». Поэтому оба вектора центрируются и штрафуются
          симметрично.
        </p>
      </Section>

      <Section title="Как проверяется честность">
        <p>
          Walk-forward: каждая модель обучается только на матчах, сыгранных до
          прогнозируемого. Dixon-Coles переобучается раз в 30 дней на
          шестилетнем окне. Никакого перемешивания и никакой подгонки под
          тестовую выборку.
        </p>
        <p>
          Вес бленда подбирался на сезонах{" "}
          {backtest?.validation_seasons.join(", ") ?? "—"} и не подгонялся под
          итоговые {backtest?.test_seasons.join(", ") ?? "—"}. Выбранный вес:{" "}
          <span className="num text-text">
            w={backtest?.chosen_weight_dc.toFixed(2) ?? "—"}
          </span>{" "}
          на Dixon-Coles, то есть смешивание с Elo не дало выигрыша.
        </p>
        <p>
          Метрика — логистика: она штрафует за уверенные неверные прогнозы.
          Наивный baseline с одинаковыми вероятностями служит порогом
          осмысленности:{" "}
          <span className="num text-text">1.078</span>.
        </p>
      </Section>

      {calibration && (
        <Section title="Снятие маржи с коэффициентов">
          <p>
            Из коэффициентов букмекера нельзя сделать вероятности напрямую: в них
            заложена маржа, в среднем{" "}
            <span className="num text-text">
              {((calibration.methods[calibration.chosen]?.mean_overround ?? 1) * 100 - 100).toFixed(1)}%
            </span>
            . Кроме того, букмекер систематически занижает вероятности
            фаворитов, то есть распределение искажено, а не просто сдвинуто.
          </p>
          <p>
            Метод выбирался по данным, а не по умолчанию: сверялись средние
            вероятности с фактическими частотами исходов. Выбран{" "}
            <span className="num text-text">{calibration.chosen}</span>, log-loss{" "}
            <span className="num text-text">
              {calibration.methods[calibration.chosen]?.logloss.toFixed(5)}
            </span>
            . Метод Шина в нашей реализации даёт параметр z около 0.44 вместо
            литературных 0.01–0.05 и перекорректирует распределение, поэтому он не
            используется — и это зафиксировано в отчёте, а не спрятано в коде.
          </p>
        </Section>
      )}

      <Section title="Что было бы следующим шагом">
        <p>
          Признаки, которых у пуассоновской модели нет по построению: форма за
          последние 3–6 матчей, дни отсыпки и конфликт календаря, доля голов из
          ударов в створ, динамика силы команды по xG. Плюс бустинг поверх
          Dixon-Coles с калибровкой вероятностей. По имеющимся данным это
          основной резерв качества.
        </p>
        <p>
          Стратегически: обгонять закрывающую линию в футболе трудно именно
          потому, что информационно мы беднее рынка. Перенос этой же модели на
          лигу с более тонким рынком — реалистичный сценарий, где преимущество
          появляется.
        </p>
      </Section>
    </div>
  );
}
