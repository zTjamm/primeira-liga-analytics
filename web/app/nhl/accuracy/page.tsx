import { getNhlJournal } from "@/lib/data";
import { AccuracySummary } from "@/components/AccuracySummary";
import { EmptyState } from "@/components/EmptyState";

export const dynamic = "force-dynamic";

export default async function NhlAccuracyPage() {
  const journal = await getNhlJournal();

  if (!journal) {
    return (
      <EmptyState
        title="Метрики НХЛ ещё не посчитаны"
        hint="Прогоните пайплайн: модель обучается на прошлых матчах, и метрики появятся в журнале."
        command="python -m models.nhl_predict"
      />
    );
  }

  const { summary } = journal;

  if (summary.total === 0) {
    return (
      <EmptyState
        title="Нет сыгранных прогнозов для оценки"
        hint="Как только в данных появятся результаты матчей, здесь будут точность, log-loss и ROI."
      />
    );
  }

  return (
    <AccuracySummary
      title="Точность модели — НХЛ"
      intro="Честная оценка: сначала ограничения, потом цифры."
      summary={summary}
      matchesHref="/nhl"
      matchesLabel="странице матчей"
      limitations={
        <>
          <li>
            Сравнения с букмекерской линией нет: коэффициентов на НХЛ в
            открытых источниках не найдено, поэтому утверждать выигрыш в
            деньгах нельзя.
          </li>
          <li>
            Точность считается только по матчам, где вердикт был выдан.
            Отсеянные матчи показаны отдельно — иначе процент выглядел бы
            лучше, чем он есть.
          </li>
          <li>
            История — девять сезонов регулярного чемпионата (2018/19 —
            2026/27), проверка идёт на 8 748 матчах walk-forward: для
            каждого сезона модель обучается только на предыдущих. Но
            строгое правило внедрения по двум последним fold&apos;ам дало
            отказ, и это публикуется на странице «Методика»: решение
            принято по всей истории, где разница устойчива, а не по двум
            последним сезонам, где она шумная.
          </li>
          <li>
            В сезоне 2025/26 аномально низкая доля домашних побед (52.2%
            против 56.2% в предыдущем), и на нём новая модель проигрывает
            прежней. Это не спрятано: fold показан в таблице методики.
          </li>
          <li>
            Статистики матча почти нет: ни бросков, ни времени во владении.
            Атака и оборона разделены только математически.
          </li>
        </>
      }
    />
  );
}
