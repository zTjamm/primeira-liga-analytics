"""Азиатский хэндикап: прогноз разницы мячей, а не победителя.

Обычный 1X2 спрашивает «кто выиграл», хэндикап — «насколько сильно».
Ставка на линию L (от视角 хозяев) выигрывает, когда разница мячей больше L.

Тонкость, из-за которой рынок нельзя считать обычным двусторонним:

* Целые линии (±1.0, ±2.0) допускают ВОЗВРАТ. Разница ровно в один мяч
  при линии -1.0 — ставка не проиграла и не выиграла. Значит, исходов
  формально три, и снятие маржи как у двухстороннего рынка неверно.
* Четверти (-0.25, -0.75) возврат исключают: ставка режется пополам на
  две соседние линии, и одна половина всегда проигрывает.

Из-за этого «просто снять маржу» здесь нельзя, а честное сравнение с
рынком возможно только на дробных линиях — там исходов ровно два.
Именно так и сделано в report().

Запуск модуля как такового не требуется — его зовёт models/predict.py.
"""
from __future__ import annotations

import numpy as np

# Линии, кратные 0.25, в порядке возрастания.
QUARTERS = (0.75, 0.5, 0.25, 0.0, -0.25, -0.5, -0.75)


def goal_difference(matrix: np.ndarray) -> dict[int, float]:
    """Распределение разницы мячей (голы хозяев минус голы гостей)."""
    n = matrix.shape[0]
    out: dict[int, float] = {}
    for i in range(n):
        for j in range(n):
            out[i - j] = out.get(i - j, 0.0) + float(matrix[i, j])
    return out


def split_line(line: float) -> list[float]:
    """Дробная линия -> список линий на равные доли ставки.

    Возвращается одна линия для целой и две для четверти. Это не
    украшение: так устроен рынок, и без этого расчёт вероятностей
    дал бы неверный ответ на четвертях.
    """
    scaled = round(line * 4)
    if scaled % 2 == 0:                     # целая или половинная
        return [round(scaled / 4, 2)]
    lo = (scaled - 1) / 4                   # четверть: -0.25 -> -0.5 и 0.0
    hi = (scaled + 1) / 4
    return sorted((lo, hi))


def cover_probs(matrix: np.ndarray, line: float) -> dict[str, float]:
    """Вероятности исходов ставки на линию: выиграл / возврат / проиграл.

    ЛИНИЯ ЗНАКОВАЯ, и это главная ловушка рынка. Линия отсчитывается от
    хозяев и ПРИБАВЛЯЕТСЯ к их голам: при -1.0 хозяева как будто забили
    на один меньше, и выигрыш получается, когда разница больше ЕДИНИЦЫ,
    а не больше нуля.

    Поэтому сравнивать надо diff > -line, а не diff > line. Ошибка знака
    незаметна на крупных счётах (3:0 при -1.0 проходит в обоих вариантах)
    и проявляется ровно там, где важен возврат: 1:0 при линии -1.0 —
    это возврат, а не победа.
    """
    d = goal_difference(matrix)
    parts = split_line(line)
    w = l = r = 0.0
    for p in parts:
        weight = 1.0 / len(parts)
        target = -p            # <- переносим линию на разницу мячей
        w += weight * sum(v for k, v in d.items() if k > target)
        l += weight * sum(v for k, v in d.items() if k < target)
        r += weight * sum(v for k, v in d.items() if k == target)
    total = w + l + r
    if total <= 0:
        return {"win": 0.0, "push": 0.0, "lose": 0.0}
    return {"win": w / total, "push": r / total, "lose": l / total}


def has_push(line: float) -> bool:
    """Вернётся ли СТАВКА ЦЕЛИКОМ.

    Только на целых линиях: тогда разница может в точность совпасть с
    линией. На четвертях возврата не бывает — одна половина ставки
    всегда проигрывает, даже если вторая вернулась. Именно поэтому
    дробные линии сравнимы с двухсторонним снятием маржи, а целые — нет.
    """
    return float(line).is_integer()


def fair_line(matrix: np.ndarray) -> float:
    """Линия, при которой обе стороны равны — медиана разницы мячей.

    Знак минусовой: сильный хозяин получает линию -1.0, то есть ЕМУ
    отнимают гол. Медиана разницы здесь положительна у такого хозяина,
    поэтому возвращается с обратным знаком — иначе подсказка читалась
    бы наоборот, а именно это и случилось в первой версии.
    """
    d = goal_difference(matrix)
    items = sorted(d.items())
    total = sum(v for _, v in items)
    acc = 0.0
    for k, v in items:
        acc += v
        if acc >= total / 2:
            return float(-(round(k * 2) / 2))
    return 0.0


def summarize(matrix: np.ndarray) -> dict:
    """Всё, что нужно показать про хэндикап по одному матчу."""
    d = goal_difference(matrix)
    total = sum(d.values()) or 1.0
    return {
        "fair_line": fair_line(matrix),
        # Разбивка, из которой складывается хэндикап: выиграть в два и
        # больше, выиграть ровно в один, не выиграть — и то же для гостей.
        "home_2plus": sum(v for k, v in d.items() if k >= 2) / total,
        "home_exactly_1": d.get(1, 0.0) / total,
        "home_0_or_away": sum(v for k, v in d.items() if k <= 0) / total,
        "away_2plus": sum(v for k, v in d.items() if k <= -2) / total,
        "away_exactly_1": d.get(-1, 0.0) / total,
        # Наиболее вероятная разница — для наглядности.
        "most_likely_diff": max(d.items(), key=lambda kv: kv[1])[0],
    }