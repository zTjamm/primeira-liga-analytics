"""Правило отказа от вердикта.

Не каждый матч стоит прогнозировать. Когда ни один исход не превышает
порог вероятности, это не сильный прогноз, а бросок монеты с тремя
гранями — и выдавать его за вердикт значит подменять «мы не знаем»
своим собственным выводом.

Порог VERDICT_THRESHOLD не подобран на глаз. Он выбран на валидационном
сезоне 2022/23 в models/selective.py по критерию «точность модели минус
точность правила "всегда на хозяев" на том же подмножестве». На трёх
тестовых сезонах он даёт покрытие 39% при точности 70.2% против 54.0%
у примитива.

Почему важно сравнение с примитивом, а не просто точность: на любом
отобранном подмножестве точность растёт сама по себе, и это ничего не
значит. Значит лишь то, что модель на своих же уверенных матчах
переигрывает тупую ставку на хозяев.

Оговорка, которую нельзя замалчивать: отбор повышает точность, ничего
не добавляя к качеству прогноза. Log-loss остаётся прежним, потому что
вероятности не меняются — меняется только решение, показывать их или нет.
"""
from __future__ import annotations

# Порог вероятности наиболее вероятного исхода, ниже которого вердикт
# не выдаётся. Обоснован в models/selective.py.
VERDICT_THRESHOLD = 0.55

# Порядок подбора: порог сравнивался с этим правилом на том же
# подмножестве. Совпадение сделано, чтобы отсев можно было проверить.
BASELINE_RULE = "всегда на хозяев"


def verdict(confidence: float,
            team_games: int | None = None,
            threshold: float = VERDICT_THRESHOLD,
            min_team_games: int = 10) -> tuple[bool, str]:
    """Решает, показывать ли вердикт.

    Возвращает (показывать, причина). Причина пустая, когда вердикт
    выдаётся — она нужна только для показа пользователю, чтобы отказ
    выглядел объяснением, а не молчанием.

    team_games — сколько матчей хотя бы у одной из команд было в
    обучающем окне. Параметры новичка выведены из данных, которых у нас
    нет, поэтому его прогноз формально есть, а по сути нет.
    """
    if confidence < threshold:
        return False, (
            f"вероятность исхода {confidence:.2f} ниже порога {threshold:.2f}: "
            "исходы почти равны, модель не различает их"
        )
    if team_games is not None and team_games < min_team_games:
        return False, (
            f"у команды всего {team_games} матчей в обучающей выборке: "
            "параметры условны, прогноз недостоверен"
        )
    return True, ""